"""Evaluator-only CSV v1 cases. Independently authored compositions per split."""
from .csv_task import validate_cases
PROFILE='commons-csv-v1'


def cases(split='visible',seed=6158):
    # Fixed authored suite; seed is metadata, not a claim of random sampling.
    if split not in ('visible','holdout'):raise ValueError('Unknown CSV split')
    rows=[]
    def parse(label,text,**config):
        rows.append({'id':f'csv-v1-{split}-{label}','task':'commons_csv','operation':'parse','text':text,'config':config})
    def print_(label,records,**config):
        rows.append({'id':f'csv-v1-{split}-{label}','task':'commons_csv','operation':'print','records':records,'config':config})
    if split=='visible':
        parse('empty','')
        parse('blank-default','\n\r\n')
        parse('blank-kept','a\n\n',ignore_empty_lines=False)
        parse('trailing-fields','a,,\nb,c,')
        parse('quoted-empty','"",x\n')
        parse('quoted-delimiter','a,"b,c"\n')
        parse('doubled-quote','"say ""hi""",end')
        parse('multiline','"line1\nline2",x\n')
        parse('mixed-endings','a,b\r\nc,d\re,f\n')
        parse('semicolon','a;"b;c";d',delimiter=';')
        parse('escaped-quote','"a\\"b",c',escape='\\')
        parse('spaces-literal',' a , b ') 
        parse('surrounding',' a , " b " ',ignore_surrounding_spaces=True)
        parse('trim',' a ," b "',trim=True)
        parse('null-marker','NULL,"NULL",,x',null_string='NULL')
        parse('unicode','α,🚀,e\u0301')
        parse('quotes-disabled','a,"b",c',quote=None)
        parse('separator-is-printer-only','a|b',record_separator='|')
        parse('unterminated','"open')
        parse('junk-after-quote','"x"junk,y')
        parse('invalid-delimiter','a,b',delimiter='\n')
        parse('invalid-bool','a',trim=1)
        parse('invalid-quote-mode','a',quote_mode='UNKNOWN')
        print_('empty-output',[])
        print_('empty-record',[[]])
        print_('basic-output',[['a','b'],['c','d']])
        print_('printer-quotes',[['a,b','say "hi"','']])
        print_('printer-multiline',[['a\nb','c\rd']])
        print_('printer-unicode',[['中','🚀',None]])
        print_('printer-null',[[None,'NULL','']],null_string='NULL')
        print_('printer-all',[['a','b']],quote_mode='ALL')
        print_('printer-all-non-null',[[None,'','x']],quote_mode='ALL_NON_NULL',null_string='N')
        print_('printer-non-numeric',[['12','x']],quote_mode='NON_NUMERIC')
        print_('printer-none',[['a,b','c\nd']],quote_mode='NONE',escape='\\')
        print_('printer-custom',[['a;b',' c ']],delimiter=';',record_separator='\n')
        print_('printer-trim',[[' a ',' b ']],trim=True)
        print_('invalid-none',[['a']],quote_mode='NONE')
    else:
        parse('multiline-empty-composition','head,"first\r\nsecond",\r\n,,tail')
        parse('blank-between-quoted-records','"a,b",c\n\n"d",\n',ignore_empty_lines=False)
        parse('quoted-quotes-and-cr','"""x""\ry",z\r')
        parse('tab-unicode','中\t"x\ty"\t🚀',delimiter='\t')
        parse('escaped-delimiter-newline','one\\,two,three\\nline',escape='\\')
        parse('spaces-with-empty',' x , ," y "\n',ignore_surrounding_spaces=True)
        parse('trim-multiline','" x\ny ", z ,',trim=True)
        parse('null-and-empty-quoted','N,"N","",\n',null_string='N',quote_mode='ALL_NON_NULL')
        parse('quoted-null-default','missing,"missing",value',null_string='missing')
        parse('literal-quotes-semicolon','"left";right;',quote=None,delimiter=';')
        parse('empty-null-marker',',"",tail',null_string='')
        parse('nul-and-supplementary','a\x00b,"🚀,😀",end')
        parse('printer-separator-does-not-split','x;y|z;w',delimiter=';',record_separator='|')
        parse('unterminated-second-record','ok,row\n"open\nnext')
        parse('junk-after-multiline-quote','"a\nb"!;c',delimiter=';')
        parse('same-quote-and-delimiter','x',delimiter='"')
        parse('invalid-ignore-type','x',ignore_empty_lines='true')
        parse('supplementary-delimiter','x',delimiter='🚀')
        print_('mixed-output',[['','x,y',None],['a\nb','"','last']])
        print_('custom-quote',[['a;b',"it's fine"]],delimiter=';',quote="'",record_separator='\n')
        print_('all-multiline-null',[[None,'x\ny','']],quote_mode='ALL',null_string='N',record_separator='\r')
        print_('non-null-markers',[[None,'N','x,y'],['','z','']],quote_mode='ALL_NON_NULL',null_string='N')
        print_('numeric-looking-strings',[['-1','1.25','NaN','']],quote_mode='NON_NUMERIC',delimiter=';')
        print_('none-escaped-custom',[['x;y','a\\b','line\r\nnext']],quote_mode='NONE',delimiter=';',escape='\\')
        print_('trim-null-and-space',[[None,' x ',' y,z ']],trim=True,null_string='MISSING')
        print_('empty-record-followed',[[],['x'],[]],record_separator='\n')
        print_('invalid-escape-mode',[['bad']],escape='\n',quote_mode='NONE')
        print_('unicode-quotes',[["α,β",'🚀\n😀','e\u0301']],quote='\u00ab')
    validate_cases(rows)
    return rows
